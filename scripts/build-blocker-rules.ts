/**
 * Write scripts/blockerRules.gen.ts: the rules from the common ad-block and tracker lists that can block a file the
 * build names after a module (`assets/<module>-<hash>.js`), for the build's name check (scripts/blockerNames.ts).
 *
 * The bundler names each shared chunk after its module, and a list rule aimed at someone's tracker can hit one of our
 * own files by name. On 2026-11-22, AdGuard's Tracking Protection rule `/clarity-*.js` (Microsoft Clarity) blocked
 * src/lib/clarity.ts's chunk. The results panel and the globe both need that chunk, so visitors with that list on got
 * the fault notice after every search, and no globe. A blocked file fails the same way whatever its name, so the
 * build refuses any name these rules match.
 *
 * Only rules that can block such a name on our own site are kept: generic (no domain, or only `~domain` exceptions),
 * not third-party-only, not anchored to a host (`||`, `|https://`), and shaped like
 *   /word-   /word-*.js   /word*   /word*.js   /word_   /word   (anchored at a path segment: the name starts with word)
 *   -word-   _word_       (anywhere in the name)
 * Rules for longer paths (`/index-ads.js`) cannot match a hashed name and are left out: checked on 2026-11-22 with a
 * real filter engine (@ghostery/adblocker) over every module name in src/, api/ and worker/ and ~80 tracker words,
 * against all the lists below. Only `clarity-` and `piwik-` were blocked, and both are in the kept set. Exception
 * rules (`@@`) are ignored: a name an exception happens to let through is still refused (stricter, never looser).
 *
 * Usage: npm run data:blocker-rules <dir with the lists>
 *   Download into the dir (any file name ending .txt):
 *     https://easylist.to/easylist/easylist.txt
 *     https://easylist.to/easylist/easyprivacy.txt
 *     https://easylist.to/easylist/fanboy-annoyance.txt
 *     https://easylist.to/easylist/fanboy-social.txt
 *     https://secure.fanboy.co.nz/fanboy-cookiemonster.txt
 *     https://filters.adtidy.org/extension/ublock/filters/2.txt   (AdGuard Base)
 *     https://filters.adtidy.org/extension/ublock/filters/3.txt   (AdGuard Tracking Protection)
 *     https://filters.adtidy.org/extension/ublock/filters/4.txt   (AdGuard Social Media)
 *     https://filters.adtidy.org/extension/ublock/filters/11.txt  (AdGuard Mobile Ads)
 *     https://filters.adtidy.org/extension/ublock/filters/14.txt  (AdGuard Annoyances)
 *     https://filters.adtidy.org/extension/ublock/filters/17.txt  (AdGuard URL Tracking)
 *     https://ublockorigin.github.io/uAssets/filters/filters.txt
 *     https://ublockorigin.github.io/uAssets/filters/privacy.txt
 *     https://ublockorigin.github.io/uAssets/filters/badware.txt
 *     https://pgl.yoyo.org/adservers/serverlist.php?hostformat=adblockplus&showintro=1&mimetype=plaintext
 *   Lists change weekly; a rebuild now and then (or when a visitor's blocker breaks the site) is enough.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

/** A rule anchored at a path segment: `/word` then one of the endings that leave the rest of the name free. */
const ANCHORED = /^\/[A-Za-z][A-Za-z0-9_]*(?:-|-\*|\*|-\*\.js|\*\.js|_|)$/
/** A rule that matches anywhere in the path: a word between separators. */
const UNANCHORED = /^[-_]?[A-Za-z][A-Za-z0-9_]*(?:-|-\*|-\*\.js|_)$/

/** The rule's pattern if it can block one of our own hashed file names by its name, else undefined. */
export function nameRule(line: string): string | undefined {
  const rule = line.trim()
  if (!rule || /^[![]/.test(rule) || rule.startsWith('@@') || /#[@?$%]?#/.test(rule)) return undefined
  if (rule.startsWith('||') || rule.startsWith('|')) return undefined
  const dollar = rule.lastIndexOf('$')
  const pattern = dollar > 0 ? rule.slice(0, dollar) : rule
  const options = dollar > 0 ? rule.slice(dollar + 1).split(',') : []
  for (const o of options) {
    if (o === 'third-party' || o === '3p' || o === 'strict3p') return undefined
    const domains = /^(?:domain|from)=(.*)$/.exec(o)?.[1]
    if (domains !== undefined && domains.split('|').some((d) => !d.startsWith('~'))) return undefined
  }
  return ANCHORED.test(pattern) || UNANCHORED.test(pattern) ? pattern : undefined
}

function main(dir: string) {
  const kept = new Map<string, string>()
  const files = readdirSync(dir).filter((f) => f.endsWith('.txt')).sort()
  if (!files.length) throw new Error(`no .txt lists in ${dir}`)
  for (const f of files)
    for (const line of readFileSync(join(dir, f), 'utf8').split(/\r?\n/)) {
      const p = nameRule(line)
      // Matching ignores case, so rules that differ only in case are one rule.
      if (p && !kept.has(p.toLowerCase())) kept.set(p.toLowerCase(), p)
    }
  const rules = [...kept.values()].sort((a, b) => a.toLowerCase().localeCompare(b.toLowerCase()))
  const out = `/**
 * Generated by scripts/build-blocker-rules.ts on ${new Date().toISOString().slice(0, 10)} from ${files.length} lists: never edit by hand.
 * Ad-block and tracker list rules that can block a file the build names after a module (scripts/blockerNames.ts).
 */
export const BLOCKER_RULES: readonly string[] = [
${rules.map((r) => `  '${r}',`).join('\n')}
]
`
  writeFileSync(new URL('./blockerRules.gen.ts', import.meta.url), out)
  console.log(`blocker rules: ${rules.length} from ${files.length} lists`)
}

if (process.argv[1] && /build-blocker-rules\.ts$/.test(process.argv[1])) {
  const dir = process.argv[2]
  if (!dir) {
    console.error('usage: npm run data:blocker-rules <dir with the lists>')
    process.exit(1)
  }
  main(dir)
}
